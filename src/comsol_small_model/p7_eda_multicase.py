from __future__ import annotations

import csv
import hashlib
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any


CHINA_TZ = timezone(timedelta(hours=8))


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _artifact(path: Path, root: Path) -> dict[str, Any]:
    exists = path.is_file()
    result: dict[str, Any] = {
        "path": path.relative_to(root).as_posix(),
        "exists": exists,
        "size_bytes": path.stat().st_size if exists else 0,
    }
    if exists:
        result["sha256"] = _sha256(path)
    return result


def _read_csv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        return list(reader.fieldnames or []), list(reader)


def _input_key(row: dict[str, str], columns: list[str]) -> tuple[str, ...]:
    # Input files are generated by deterministic scripts. Normalizing through
    # float formatting prevents harmless textual differences such as 400/400.0.
    values: list[str] = []
    for column in columns:
        raw = str(row.get(column, "")).strip()
        try:
            values.append(format(float(raw), ".12g"))
        except ValueError:
            values.append(raw)
    return tuple(values)


def _relative_validation(report: dict[str, Any]) -> tuple[bool, dict[str, Any]]:
    outputs = report.get("per_output_relative_validation", {})
    output_checks: dict[str, Any] = {}
    if isinstance(outputs, dict) and outputs:
        for name, item in outputs.items():
            if not isinstance(item, dict):
                output_checks[str(name)] = {"passed": False, "reason": "invalid output report"}
                continue
            maximum = float(item.get("max_relative_error_percent", float("inf")))
            threshold = float(item.get("threshold_relative_error_percent", float("-inf")))
            output_checks[str(name)] = {
                "max_relative_error_percent": maximum,
                "threshold_relative_error_percent": threshold,
                "passed": bool(item.get("passed")) and maximum <= threshold,
            }
    else:
        maximum = float(report.get("max_relative_error_percent", float("inf")))
        threshold = float(report.get("threshold_relative_error_percent", float("-inf")))
        output_checks["all_outputs"] = {
            "max_relative_error_percent": maximum,
            "threshold_relative_error_percent": threshold,
            "passed": maximum <= threshold,
        }
    passed = bool(report.get("passed")) and bool(output_checks) and all(
        bool(item.get("passed")) for item in output_checks.values()
    )
    return passed, output_checks


def _p5_validation(report: dict[str, Any]) -> tuple[bool, dict[str, Any]]:
    counts = report.get("counts", {}) if isinstance(report.get("counts"), dict) else {}
    checks = {
        "comsol_execution_passed": bool(report.get("execution_passed")),
        "surrogate_release_passed": bool(report.get("surrogate_release_passed")),
        "false_safe_zero": int(counts.get("false_safe_upper_95", -1)) == 0,
        "safe_release_coverage_at_least_0_10": float(report.get("safe_release_coverage", 0.0)) >= 0.10,
    }
    return all(checks.values()), checks


def evaluate_case(case: dict[str, Any], root: Path) -> dict[str, Any]:
    paths = {
        key: root / str(case[key])
        for key in ("training_csv", "holdout_csv", "validation_report", "model_artifact", "comsol_artifact")
    }
    artifacts = {name: _artifact(path, root) for name, path in paths.items()}
    required_files_present = all(item["exists"] and item["size_bytes"] > 0 for item in artifacts.values())

    input_columns = [str(item) for item in case.get("input_columns", [])]
    training_rows: list[dict[str, str]] = []
    holdout_rows: list[dict[str, str]] = []
    training_columns: list[str] = []
    holdout_columns: list[str] = []
    csv_error = ""
    if artifacts["training_csv"]["exists"] and artifacts["holdout_csv"]["exists"]:
        try:
            training_columns, training_rows = _read_csv(paths["training_csv"])
            holdout_columns, holdout_rows = _read_csv(paths["holdout_csv"])
        except (OSError, csv.Error, UnicodeError) as exc:
            csv_error = str(exc)

    columns_present = bool(input_columns) and all(
        column in training_columns and column in holdout_columns for column in input_columns
    )
    training_keys = {_input_key(row, input_columns) for row in training_rows} if columns_present else set()
    holdout_keys = {_input_key(row, input_columns) for row in holdout_rows} if columns_present else set()
    overlap = sorted(training_keys & holdout_keys)
    row_checks = {
        "training_rows": len(training_rows),
        "minimum_training_rows": int(case.get("minimum_training_rows", 1)),
        "training_rows_passed": len(training_rows) >= int(case.get("minimum_training_rows", 1)),
        "holdout_rows": len(holdout_rows),
        "minimum_holdout_rows": int(case.get("minimum_holdout_rows", 1)),
        "holdout_rows_passed": len(holdout_rows) >= int(case.get("minimum_holdout_rows", 1)),
        "input_columns_present": columns_present,
        "input_overlap_count": len(overlap),
        "independent_holdout_passed": columns_present and not overlap,
    }
    if csv_error:
        row_checks["csv_error"] = csv_error

    validation_report: dict[str, Any] = {}
    validation_error = ""
    if artifacts["validation_report"]["exists"]:
        try:
            validation_report = json.loads(paths["validation_report"].read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            validation_error = str(exc)
    mode = str(case.get("validation_mode", "relative_error_gate"))
    if mode == "p5_release_gate":
        validation_passed, validation_checks = _p5_validation(validation_report)
        evidence_tier = "fresh_current_project_comsol_closed_loop"
    else:
        validation_passed, validation_checks = _relative_validation(validation_report)
        evidence_tier = "historical_independent_comsol_holdout"
    if validation_error:
        validation_checks["report_error"] = validation_error
        validation_passed = False

    checks = {
        "required_files_present": required_files_present,
        "row_requirements_passed": bool(row_checks["training_rows_passed"] and row_checks["holdout_rows_passed"]),
        "independent_holdout_passed": bool(row_checks["independent_holdout_passed"]),
        "validation_passed": validation_passed,
    }
    return {
        "id": str(case["id"]),
        "name_zh": str(case["name_zh"]),
        "role": str(case.get("role", "main")),
        "physics_family": str(case["physics_family"]),
        "evidence_tier": evidence_tier,
        "passed": all(checks.values()),
        "checks": checks,
        "dataset": row_checks,
        "validation": {"mode": mode, "checks": validation_checks},
        "artifacts": artifacts,
    }


def build_p7_report(root: str | Path, config_path: str | Path | None = None) -> dict[str, Any]:
    project_root = Path(root).resolve()
    config_file = Path(config_path).resolve() if config_path else project_root / "configs" / "p7_eda_multicase_benchmark.json"
    config = json.loads(config_file.read_text(encoding="utf-8"))
    cases = [evaluate_case(case, project_root) for case in config.get("cases", [])]
    main_cases = [case for case in cases if case["role"] == "main"]
    extension_cases = [case for case in cases if case["role"] != "main"]
    passed_main = [case for case in main_cases if case["passed"]]
    physics_families = sorted({case["physics_family"] for case in passed_main})
    acceptance = config.get("acceptance", {})
    gates = {
        "minimum_main_cases": len(passed_main) >= int(acceptance.get("minimum_main_cases", 4)),
        "minimum_physics_families": len(physics_families) >= int(acceptance.get("minimum_physics_families", 4)),
        "all_main_cases_passed": bool(main_cases) and len(passed_main) == len(main_cases),
        "all_main_holdouts_independent": bool(main_cases) and all(
            case["checks"]["independent_holdout_passed"] for case in main_cases
        ),
    }
    completed = all(gates.values())
    return {
        "schema": "comsol-p7-eda-multicase-report",
        "schemaVersion": "1.0.0",
        "generated_at": datetime.now(CHINA_TZ).isoformat(),
        "phase": "P7",
        "title": "多 EDA 案例与可扩展性验证",
        "status": "completed" if completed else "needs_evidence",
        "p7_completed": completed,
        "main_case_count": len(main_cases),
        "passed_main_case_count": len(passed_main),
        "extension_case_count": len(extension_cases),
        "passed_extension_case_count": sum(1 for case in extension_cases if case["passed"]),
        "physics_family_count": len(physics_families),
        "physics_families": physics_families,
        "gates": gates,
        "cases": cases,
        "config": _artifact(config_file, project_root),
        "claim_boundary": (
            "P7 demonstrates a repeatable evidence and validation contract across several EDA physics families. "
            "Only the busbar case is a fresh current-project COMSOL closed loop; the other cases use preserved "
            "independent COMSOL holdouts and are reported as historical evidence. P6 external experiment and "
            "human-baseline gates remain separate."
        ),
    }


def write_p7_report(
    root: str | Path,
    output_path: str | Path | None = None,
    config_path: str | Path | None = None,
) -> dict[str, Any]:
    project_root = Path(root).resolve()
    report = build_p7_report(project_root, config_path=config_path)
    destination = Path(output_path).resolve() if output_path else project_root / "generated" / "p7" / "p7_eda_multicase_report.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    report["report_path"] = destination.relative_to(project_root).as_posix()
    return report
